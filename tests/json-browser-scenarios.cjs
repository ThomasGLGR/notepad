const assert = require('node:assert/strict');
module.exports = async function jsonChecks({evaluate,command,click,fill,wait,ready,keypress,fs,path,profile}) {
  const current=()=>evaluate('SOCNote.storage.load().document');
  const report=()=>evaluate('SOCNote.report.getText()');
  await click('#new-button');
  await fill('#rule-input','JSON investigation');
  await fill('#analysis-input','Existing analyst notes.');
  await fill('#raw-input','Existing: Kept');
  await click('#process-source-button');
  await evaluate('SOCNote.remediation.setActiveTactics(["credential-access"]); document.querySelector("[data-choose=credential-access-1]").click();');
  await fill('[data-selected-text=credential-access-1]','Keep this selected action.');
  const data=[{'user.name':'alice','host.hostname':'ONE','process.command_line':'first line\n\n  second line'},{'host.hostname':'TWO'},{'host.hostname':'TWO'}];
  const result=await evaluate(`importJSON(${JSON.stringify(data)},{requestId:'manual-json-one'})`);
  assert.equal(result.ok,true,result.error);
  assert.equal(result.jsonCount,4);
  const before=await current();
  assert.equal(before.rule,'JSON investigation');assert.equal(before.analysis,'Existing analyst notes.');
  assert.equal(before.remediation.selected[0].text,'Keep this selected action.');
  assert.equal(before.variables.find(record=>record.value==='TWO').key,'host.hostname2');
  assert.equal(await evaluate('document.querySelector("textarea[data-variable-value]").value'),'first line\n\n  second line');
  const textBefore=await report();
  assert.equal((await evaluate(`SOCNote.importJSON(${JSON.stringify(data)},{requestId:'manual-json-one'})`)).count,0);
  assert.equal(await report(),textBefore);
  assert.equal((await evaluate('SOCNote.importJSON({"host.hostname":"DIFFERENT"},{requestId:"manual-json-one"})')).ok,false);
  assert.equal(await report(),textBefore);
  await command('Page.reload');await ready();
  assert.equal(await report(),textBefore);
  assert.equal((await evaluate(`importJSON(${JSON.stringify(data)},{requestId:'manual-json-one'})`)).count,0);
  const valueId=before.variables.find(record=>record.key==='process.command_line').id;
  await click('[data-copy-variable="'+valueId+'"]');await wait(40);
  assert.equal(await evaluate('navigator.clipboard.readText()'),'first line\n\n  second line');
  // Failure is reported and neither visible facts nor the saved receipt change.
  await evaluate('window.jsonTestSetItem=Storage.prototype.setItem; Storage.prototype.setItem=function(){throw Error("Forced quota");};');
  assert.equal((await evaluate('importJSON({"new.field":"Not yet committed"},{requestId:"blocked-json"})')).ok,false);
  assert.equal(await report(),textBefore);
  await evaluate('Storage.prototype.setItem=window.jsonTestSetItem;');
  assert.equal((await evaluate('importJSON({"new.field":"Not yet committed"},{requestId:"blocked-json"})')).ok,true);
  // Opening JSON appends fields without replacing pending Logs or notes.
  await fill('#raw-input','Pending: Keep this source');await wait(300);
  const jsonFile=path.join(profile,'siem-export.json');
  await fs.writeFile(jsonFile,JSON.stringify([{'file.field':'From JSON file'},{'file.field':'Another file value'}]));
  const {root}=await command('DOM.getDocument');
  const {nodeId}=await command('DOM.querySelector',{nodeId:root.nodeId,selector:'#log-file-input'});
  await command('DOM.setFileInputFiles',{nodeId,files:[jsonFile]});
  for(let attempt=0;attempt<60;attempt++) {if((await report()).includes('Another file value'))break;await wait(30);}
  assert((await report()).includes('file.field2: Another file value'));
  assert.equal(await evaluate('document.getElementById("raw-input").value'),'Pending: Keep this source');
  assert.equal(await evaluate('document.getElementById("analysis-input").value'),'Existing analyst notes.');
  // A clipboard JSON array uses the same import path when pasted into Logs.
  await fill('#raw-input','');
  await evaluate('navigator.clipboard.writeText("[{\\"clipboard.field\\":\\"A\\"},{\\"clipboard.field\\":\\"B\\"}]")');
  await evaluate('document.getElementById("raw-input").focus()');
  await keypress('v','KeyV',2,86);
  await wait(100);
  assert((await report()).includes('clipboard.field2: B'));
  const clipboardId=()=>evaluate('Array.from(document.querySelectorAll("[data-variable-id]")).find(node=>node.querySelector("[data-variable-value]").value==="B").dataset.variableId');
  const deletedId=await clipboardId();
  await click('[data-pair-action=remove][data-id="'+deletedId+'"]');
  assert(!(await report()).includes('clipboard.field2: B'));
  await evaluate('document.getElementById("raw-input").focus();document.getElementById("raw-input").select()');
  await keypress('v','KeyV',2,86);await wait(100);
  assert((await report()).includes('clipboard.field2: B'),'Repasting identical pending JSON restores a deleted value');
  const restoredId=await clipboardId();
  assert.notEqual(restoredId,deletedId);
  await keypress('Enter','Enter',2,13);
  assert.equal(await evaluate('document.getElementById("raw-input").value'),'');
  assert(!(await evaluate('document.getElementById("toast").textContent')).includes('already imported'),'Submitting pasted JSON does not claim it was blocked');
  await click('[data-pair-action=remove][data-id="'+restoredId+'"]');
  await evaluate('document.getElementById("raw-input").focus()');
  await keypress('v','KeyV',2,86);await wait(100);
  await keypress('Enter','Enter',2,13);
  assert((await report()).includes('clipboard.field2: B'),'Identical JSON pasted after submission also restores a deleted value');
  assert.equal(await evaluate('Array.from(document.querySelectorAll("[data-variable-value]"),node=>node.value).filter(value=>value==="B").length'),1,'Reimported JSON values stay unique');
  assert.equal(await evaluate('document.getElementById("raw-input").value'),'');
  assert((await report()).includes('host.hostname2: TWO'));
  const validReport=await report();
  await fill('#raw-input','{"broken":');await wait(300);
  await keypress('Enter','Enter',2,13);
  assert.equal(await report(),validReport);
  assert.equal(await evaluate('document.getElementById("raw-input").value'),'{"broken":');
  assert((await evaluate('document.getElementById("toast").textContent')).includes('Invalid JSON'));
  await click('#new-button');
  const squad=JSON.parse(await fs.readFile(path.join(__dirname,'fixtures/superhero-squad.json'),'utf8'));
  assert.equal((await evaluate(`importJSON(${JSON.stringify(squad)},{requestId:'squad-example'})`)).ok,true);
  const squadDraft=await current();
  assert.equal(squadDraft.variables.length,25);
  assert.equal(squadDraft.variables.find(record=>record.key==='name').value,'Molecule Man');
  assert.equal(squadDraft.variables.find(record=>record.key==='name2').value,'Madame Uppercut');
  assert.equal(squadDraft.variables.find(record=>record.key==='name3').value,'Eternal Flame');
  assert((await report()).includes('name: Molecule Man'));
  assert(!(await report()).includes('members:'));
  await click('#new-button');
  console.log('JSON browser checks passed: central API, dotted keys, repeated values and send IDs, multiline editing/copy, autosave recovery, atomic failures, JSON file append and JSON paste/submission without changing notes or selected actions.');
};
