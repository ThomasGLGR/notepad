const assert=require('node:assert/strict');
module.exports=async function urlChecks({evaluate,command,click,fill,wait,ready,keypress}) {
  await click('#new-button');
  await evaluate('window.nativeClipboard=navigator.clipboard');
  await fill('#rule-input','URL investigation');
  await fill('#raw-input','URL: https://example.invalid/path\nuser: alice\nip: 192.0.2.1\nprocess: powershell.exe');
  await click('#process-source-button');
  const id=await evaluate('document.querySelector("#report-input [data-variable-id]").dataset.variableId');
  const input='[data-variable-value="'+id+'"]';
  const toggle='[data-defang-url="'+id+'"]';
  assert.equal(await evaluate('Array.from(document.querySelectorAll(".summary-url-option")).filter(node=>!node.hidden).length'),1);
  assert.equal(await evaluate(`document.querySelector('${toggle}').getAttribute('aria-pressed')`),'false');
  await click(toggle);
  assert.equal(await evaluate(`document.querySelector('${input}').value`),'hxxps://example[.]invalid/path');
  assert((await evaluate('SOCNote.report.getText()')).includes('URL: hxxps://example[.]invalid/path'));
  await click('[data-copy-variable="'+id+'"]');await wait(40);
  assert.equal(await evaluate('nativeClipboard.readText()'),'hxxps://example[.]invalid/path');
  await click('#copy-summary-button');await wait(40);
  assert((await evaluate('nativeClipboard.readText()')).startsWith('hxxps://example[.]invalid/path\n'));
  await click('#copy-report-button');await wait(40);
  assert.equal(await evaluate('nativeClipboard.readText()'),await evaluate('SOCNote.report.getText()'));
  await wait(250);
  assert.equal(await evaluate(`SOCNote.storage.load().document.variables.find(record=>record.id==='${id}').value`),'https://example.invalid/path');
  assert.equal(await evaluate(`SOCNote.storage.load().document.variables.find(record=>record.id==='${id}').defangUrl`),true);
  await command('Page.reload');await ready();
  await evaluate('window.nativeClipboard=navigator.clipboard');
  assert.equal(await evaluate(`document.querySelector('${toggle}').getAttribute('aria-pressed')`),'true');
  assert.equal(await evaluate(`document.querySelector('${input}').value`),'hxxps://example[.]invalid/path');

  // Editing exposes the original value and updates the existing pair rather than overwriting raw logs.
  await evaluate(`document.querySelector('${input}').focus()`);
  assert.equal(await evaluate(`document.querySelector('${input}').value`),'https://example.invalid/path');
  await fill(input,'https://other.invalid/new');
  await click('#copy-summary-button');
  assert.equal(await evaluate(`document.querySelector('${input}').value`),'hxxps://other[.]invalid/new');
  await click(toggle);
  assert.equal(await evaluate(`document.querySelector('${input}').value`),'https://other.invalid/new');
  await click('#undo-button');
  assert.equal(await evaluate(`document.querySelector('${toggle}').getAttribute('aria-pressed')`),'true');
  await fill(input,'not a URL');
  await click('#copy-summary-button');
  assert.equal(await evaluate(`document.querySelector('${toggle}').hidden`),true);
  assert((await evaluate('SOCNote.report.getText()')).includes('URL: not a URL'));
  await fill(input,'hxxps://already[.]invalid');
  await click('#copy-summary-button');
  assert.equal(await evaluate(`document.querySelector('${toggle}').hidden`),false);
  assert.equal(await evaluate(`document.querySelector('${input}').value`),'hxxps://already[.]invalid');
  assert.equal(await evaluate('document.querySelectorAll("img:not(.app-logo)").length'),0);
  await click('#new-button');
  console.log('URL checks passed: URL-only option, opt-in display, value/report copying, original preservation, draft recovery, inline editing, Undo and idempotent defanging.');
};
