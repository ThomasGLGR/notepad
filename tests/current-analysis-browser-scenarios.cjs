const assert=require('node:assert/strict');
module.exports=async function currentAnalysisChecks({evaluate,command,click,fill,wait,ready,keypress,fs,path,downloadPath,profile,events}) {
  const report=()=>evaluate('SOCNote.report.getText()');
  const current=()=>evaluate('SOCNote.storage.load().document');
  const downloads=()=>events.filter(event=>event.method==='Browser.downloadWillBegin');
  await click('#new-button');
  await evaluate('window.nativeClipboard=navigator.clipboard');
  assert.equal(await evaluate('document.querySelectorAll(".workflow-nav, .section-kicker, .brand-mark, .local-badge, #persist-input").length'),0);
  assert.equal(await evaluate('document.getElementById("source-heading").textContent'),'Logs');
  assert.equal(await evaluate('document.getElementById("rule-input").getBoundingClientRect().bottom <= document.querySelector(".source-pane").getBoundingClientRect().top'),true);
  assert.equal(await evaluate('document.querySelector("#save-report-button")'),null);
  assert.equal(await evaluate('typeof SOCNote.reportExport'),"undefined");
  assert.equal(await evaluate('document.title'),"Notepad++++");
  assert.equal(await evaluate('document.querySelector("h1").textContent'),"Notepad++++");
  await evaluate('nativeClipboard.writeText("Suspicious PowerShell Execution")');
  await evaluate('document.getElementById("rule-input").focus()');
  await keypress('v','KeyV',2,86);
  assert.equal(await evaluate('document.querySelector(".report-title").textContent'),'Suspicious PowerShell Execution');
  const raw='# RAW_ONLY_NOT_FOR_REPORT\r\nUser: alice\r\nHost: ONE\r\nIP: 192.0.2.1';
  await evaluate(`nativeClipboard.writeText(${JSON.stringify(raw+'\r\n')})`);
  await evaluate('document.getElementById("raw-input").focus()');
  await keypress('v','KeyV',2,86);
  await click('#process-source-button');
  const userId=await evaluate('document.querySelector("#report-input [data-variable-id]").dataset.variableId');
  await fill('[data-variable-value="'+userId+'"]','DOMAIN\\jdupont');
  await evaluate('SOCNote.remediation.setActiveTactics(["credential-access"])');
  await click('[data-tactic-group=credential-access] [data-choose=credential-access-1]');
  await fill('[data-selected-text=credential-access-1]','Reset this account password today.');
  await fill('#analysis-input','Sign-ins and process activity reviewed.');
  await wait(300);
  assert.equal(downloads().length,0,'Draft changes never download files');
  const before=await current();
  assert.equal(before.rule,'Suspicious PowerShell Execution');
  assert.equal(before.capturedRaw,raw);
  assert.equal(before.variables.find(record=>record.id===userId).value,'DOMAIN\\jdupont');
  assert.equal(before.remediation.selected[0].text,'Reset this account password today.');
  const expected=await report();
  assert.equal(await evaluate('document.getElementById("final-report-input").textContent'),expected);
  assert(expected.startsWith('Suspicious PowerShell Execution\n\n==================================================\n                     SUMMARY\n==================================================\n\n'));
  assert(!expected.includes('RAW_ONLY_NOT_FOR_REPORT'));
  assert(!expected.includes('schemaVersion'));
  assert(!expected.includes(userId));
  await command('Page.reload');await ready();
  await evaluate('window.nativeClipboard=navigator.clipboard');
  assert.equal(await report(),expected);
  assert.equal(await evaluate('document.getElementById("analysis-input").value'),'Sign-ins and process activity reviewed.');
  assert.equal(await evaluate('document.querySelector("[data-selected-text=credential-access-1]").value'),'Reset this account password today.');
  assert.equal(downloads().length,0);
  await click('#copy-report-button');await wait(60);
  assert.equal(await evaluate('nativeClipboard.readText()'),expected);
  assert.equal(downloads().length,0);

  // Source-file import retains provenance, while its raw comments stay out of the report.
  await click('#new-button');
  assert.equal(await current(),null);
  assert.equal(await evaluate('localStorage.getItem("soc-note-builder.current-analysis.v1")'),null);
  assert.equal(await report(),'');
  assert.equal(await evaluate('document.getElementById("rule-input").value'),'');
  assert.equal(await evaluate('document.getElementById("raw-input").value'),'');
  assert.equal(await evaluate('document.querySelectorAll("[data-selected-text]").length'),0);
  assert.equal(await evaluate('document.getElementById("analysis-input").value'),'');
  const source=path.join(profile,'Alert-45821.log');
  await fs.writeFile(source,'# FILE_RAW_ONLY\nHost: PC-0042\nIP: 185.42.21.8');
  await fill('#rule-input','Rule <>:"/\\|?*');
  const {root}=await command('DOM.getDocument');
  const {nodeId}=await command('DOM.querySelector',{nodeId:root.nodeId,selector:'#log-file-input'});
  await command('DOM.setFileInputFiles',{nodeId,files:[source]});
  for(let i=0;i<50;i++){if(await evaluate('document.getElementById("source-filename").textContent === "Alert-45821.log"'))break;await wait(30);}
  await wait(300);
  assert.equal((await current()).sourceFileName,'Alert-45821.log');
  const second=await report();
  assert(!second.includes('FILE_RAW_ONLY'));
  assert.equal(second,await evaluate('document.getElementById("final-report-input").textContent'));
  assert.equal(downloads().length,0);
  assert.deepEqual(await fs.readdir(downloadPath),[]);
  await click('#new-button');await wait(300);
  await command('Page.reload');await ready();
  assert.equal(await current(),null);
  assert.equal(await report(),'');
  assert.equal(downloads().length,0);
  console.log('Current Analysis checks passed: Notepad++++ name, Rule paste/title, automatic draft restore, New Investigation clearing, clipboard fidelity, source-file import, and no file-saving controls or downloads.');
};
