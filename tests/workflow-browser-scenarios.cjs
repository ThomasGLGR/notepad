const assert = require('node:assert/strict');

module.exports = async function workflowChecks({ evaluate, command, click, fill, wait, ready, keypress }) {
  const archived = () => evaluate('(() => {window.dispatchEvent(new Event("pagehide"));return SOCNote.storage.load().document?.capturedRaw || "";})()');
  await click('#new-button');
  await evaluate('window.nativeClipboard = navigator.clipboard');
  // Outer blank lines are dropped on arrival; the source is otherwise kept exactly.
  const raw = 'USER: DOMAIN\\jdupont\r\nHOST: PC-0042\r\nIP: 185.42.21.8';
  await evaluate(`nativeClipboard.writeText(${JSON.stringify(raw + '\r\n')})`);
  await evaluate('document.getElementById("raw-input").focus()');
  await keypress('v', 'KeyV', 2, 86);
  await keypress('Enter', 'Enter', 2, 13);
  assert.equal(await evaluate('document.getElementById("raw-input").value'), '');
  assert.equal(await archived(),raw,'Ctrl+Enter retains the original Logs without adding a newline');
  assert.equal(await evaluate('document.activeElement.id'),'raw-input');
  assert.equal(await evaluate('document.querySelectorAll("#report-input [data-variable-id]").length'), 3);
  assert((await evaluate('SOCNote.summary.getText()')).includes('DOMAIN\\jdupont'));
  assert.equal(await evaluate('document.querySelectorAll(".source-archive, #copy-raw-button, #archived-raw-input").length'),0,'The Raw Text block has been removed');
  await evaluate('SOCNote.remediation.setActiveTactics(["credential-access", "command-and-control"])');
  await click('[data-tactic-group=credential-access] [data-choose=credential-access-1]');
  await click('[data-tactic-group=command-and-control] [data-choose=command-and-control-1]');
  await fill('#analysis-input', 'Sign-ins and network activity reviewed.');
  let report = await evaluate('SOCNote.report.getText()');
  assert(report.startsWith('==================================================\n                     SUMMARY\n==================================================\n\n'));
  assert(!report.includes('REMEDIATION'), 'Withdrawn section stays out of the report');
  assert(report.includes('USER: DOMAIN\\jdupont\n\nHOST: PC-0042\n\nIP: 185.42.21.8 → VirusTotal\n'));
  assert(report.endsWith('==================================================\n                     ANALYSIS\n==================================================\n\nSign-ins and network activity reviewed.'));
  await click('#copy-report-button');
  await wait(50);
  assert.equal(await evaluate('nativeClipboard.readText()'), report);
  await fill('#raw-input', 'IP: 192.0.2.1');
  await click('#process-source-button');
  assert.equal(await evaluate('document.getElementById("raw-input").value'), '');
  assert.equal(await evaluate('document.querySelectorAll("#report-input [data-variable-id]").length'), 4);
  assert.equal(await evaluate('document.querySelector("[data-selected-text=command-and-control-1]").value'), 'Block the IP address 185[.]42[.]21[.]8 / 192[.]0[.]2[.]1.');
  assert.equal(await evaluate('document.querySelector("[data-selected-text=credential-access-1]").value'), 'Reset the password for the account DOMAIN\\jdupont.');
  await fill('#raw-input', 'HOST: PC-0043');
  await keypress('Enter', 'Enter', 2, 13);
  assert((await evaluate('SOCNote.summary.getText()')).includes('HOST : PC-0042'));
  assert((await evaluate('SOCNote.summary.getText()')).includes('HOST : PC-0043'));
  assert.equal(await evaluate('document.getElementById("analysis-input").value'), 'Sign-ins and network activity reviewed.');
  assert.equal(await evaluate('document.querySelectorAll("[data-selected-text]").length'), 2);
  await click('#process-source-button');
  assert.equal(await evaluate('document.querySelectorAll("#report-input [data-variable-id]").length'), 5);
  await click('#undo-button');
  assert.equal(await evaluate('document.getElementById("raw-input").value'), 'HOST: PC-0043');
  await evaluate('document.getElementById("raw-input").focus()');
  await keypress('Enter', 'Enter', 2, 13);
  await evaluate('window.dispatchEvent(new Event("pagehide"))');
  const stored = await evaluate('SOCNote.storage.load().document');
  assert.equal(stored.capturedRaw, raw + '\n\nIP: 192.0.2.1\n\nHOST: PC-0043');
  assert.equal(stored.analysis, 'Sign-ins and network activity reviewed.');
  assert(stored.variables.filter(variable=>variable.origin!=='mitre').every(variable => variable.origin === 'captured'));
  report = await evaluate('SOCNote.report.getText()');
  await command('Page.reload');
  await ready();
  assert.equal(await evaluate('SOCNote.report.getText()'), report);
  assert.equal(await evaluate('document.getElementById("raw-input").value'), '');
  assert(await evaluate('localStorage.getItem("soc-note-builder.current-analysis.v1")') !== null);
  await click('#new-button');
  assert.equal(await evaluate('document.getElementById("analysis-input").value'), '');
  assert.equal(await evaluate('SOCNote.report.getText()'), '');
  assert.equal(await archived(), '');
  // Enter still inserts a line break; Ctrl+Enter submits only from Logs.
  await fill('#raw-input','Pending: keep');
  await command('Input.dispatchKeyEvent',{type:'keyDown',key:'Enter',code:'Enter',windowsVirtualKeyCode:13,text:'\r',unmodifiedText:'\r'});
  await command('Input.dispatchKeyEvent',{type:'keyUp',key:'Enter',code:'Enter',windowsVirtualKeyCode:13});
  assert.equal(await evaluate('document.getElementById("raw-input").value'),'Pending: keep\n');
  assert.equal(await archived(),'');
  await fill('#analysis-input','Analysis');
  await keypress('Enter','Enter',2,13);
  assert.equal(await evaluate('document.getElementById("raw-input").value'),'Pending: keep\n','Ctrl+Enter in Analysis does not submit Logs');
  assert.equal(await archived(),'');
  await click('#new-button');
  console.log('Workflow browser checks passed: Ctrl+Enter in Logs matches Add to summary, Enter retains line breaks, other fields do not submit, exact source and values are preserved, analysis and selections stay intact, repeated imports update, the complete report copies, Undo works and saved investigations restore.');
};
